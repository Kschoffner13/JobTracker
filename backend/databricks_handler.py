    def store_application(self, email_data: Dict[str, Any]) -> bool:
        """Store job application data in Databricks"""
        try:
            with self.connection.cursor() as cursor:
                extracted = email_data.get('extracted_info', {})
                keywords_list = extracted.get('keywords_found', [])
                company_name = extracted.get('company', 'Unknown')
                job_title = extracted.get('job_title', 'Not specified')
                sender = email_data.get('from', '')

                # Resolve dimensions
                company_dim_id = self.get_or_create_company(company_name)
                job_title_dim_id = self.get_or_create_job_title(job_title)
                date_dim_id = self.get_or_create_date(email_data.get('date', ''))
                sender_dim_id = self.get_or_create_sender(sender)

                # Insert into fact_applications
                cursor.execute(f"""
                INSERT INTO {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.fact_applications
                (message_id, company_dim_id, job_title_dim_id, sender_dim_id, date_dim_id,
                 to_email, subject, application_status, application_url, received_timestamp,
                 email_body, keywords)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    email_data['message_id'],
                    company_dim_id,
                    job_title_dim_id,
                    sender_dim_id,
                    date_dim_id,
                    email_data.get('to', ''),
                    email_data.get('subject', ''),
                    extracted.get('application_status', ''),
                    extracted.get('application_url', ''),
                    email_data.get('timestamp', None),
                    email_data.get('body', '')[:5000],
                    ','.join(keywords_list)
                ))

                # Get the application_id
                cursor.execute(f"""
                SELECT application_id FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.fact_applications
                WHERE message_id = ?
                """, (email_data['message_id'],))
                app_id = cursor.fetchone()[0]

                # Sync to analytics table (flattened)
                self._sync_to_analytics(app_id)
                print(f"Stored application (fact) id={app_id} company={company_name}")
                return True
        except Exception as e:
            if 'UNIQUE constraint failed' in str(e) or 'unique' in str(e).lower():
                print(f"Message already stored: {email_data.get('message_id')}")
                return False
            print(f"Error storing application: {e}")
            return False
    
    def _sync_to_analytics(self, application_id: int):
        """Sync a single application to the analytics denormalized table"""
        try:
            with self.connection.cursor() as cursor:
                # Get the fact row and join to dimensions
                cursor.execute(f"""
                SELECT 
                    fa.application_id,
                    fa.message_id,
                    dc.company_name,
                    fa.company_dim_id,
                    dj.title,
                    fa.job_title_dim_id,
                    ds.sender_email,
                    fa.to_email,
                    fa.subject,
                    dd.the_date,
                    fa.application_status,
                    fa.application_url,
                    fa.received_timestamp,
                    fa.email_body,
                    fa.keywords,
                    fa.processed_timestamp
                FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.fact_applications fa
                LEFT JOIN {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_company dc
                    ON fa.company_dim_id = dc.company_dim_id
                LEFT JOIN {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_job_title dj
                    ON fa.job_title_dim_id = dj.job_title_dim_id
                LEFT JOIN {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_sender ds
                    ON fa.sender_dim_id = ds.sender_dim_id
                LEFT JOIN {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_date dd
                    ON fa.date_dim_id = dd.date_dim_id
                WHERE fa.application_id = ?
                """, (application_id,))

                result = cursor.fetchone()
                if not result:
                    return

                # Insert into analytics table (flattened)
                cursor.execute(f"""
                INSERT INTO {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.applications_analytics
                (application_id, message_id, company_name, company_id, job_title, job_title_id,
                 from_email, to_email, subject, email_date, application_status, application_url,
                 received_timestamp, keywords_found, email_body_length, processed_timestamp)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    result[0], result[1], result[2], result[3], result[4], result[5],
                    result[6], result[7], result[8], str(result[9]) if result[9] else None,
                    result[10], result[11], result[12], result[14] if result[14] else '',
                    len(result[13]) if result[13] else 0, result[15]
                ))
        
        except Exception as e:
            print(f"Error syncing to analytics: {e}")
    
    def get_all_applications(self, limit: int = 100) -> List[Dict[str, Any]]:
        """Retrieve all applications from analytics table (denormalized)"""
        try:
            with self.connection.cursor() as cursor:
                query = f"""
                SELECT * FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.applications_analytics
                ORDER BY processed_timestamp DESC
                LIMIT {limit}
                """
                cursor.execute(query)
                columns = [description[0] for description in cursor.description]
                results = []
                for row in cursor.fetchall():
                    results.append(dict(zip(columns, row)))
                return results
        
        except Exception as e:
            print(f"Error retrieving applications: {e}")
            return []
    
    def get_applications_by_status(self, status: str, limit: int = 50) -> List[Dict[str, Any]]:
        """Retrieve applications filtered by status from analytics table"""
        try:
            with self.connection.cursor() as cursor:
                query = f"""
                SELECT * FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.applications_analytics
                WHERE application_status = ?
                ORDER BY processed_timestamp DESC
                LIMIT {limit}
                """
                cursor.execute(query, (status,))
                columns = [description[0] for description in cursor.description]
                results = []
                for row in cursor.fetchall():
                    results.append(dict(zip(columns, row)))
                return results
        
        except Exception as e:
            print(f"Error retrieving applications by status: {e}")
            return []
    
    def close(self):
        """Close Databricks connection"""
        if self.connection:
            self.connection.close()
