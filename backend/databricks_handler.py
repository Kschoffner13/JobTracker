    def get_or_create_date(self, date_str: str) -> int:
        """Get date_dim_id or create new date dimension. Expects ISO date string or empty."""
        try:
            if not date_str:
                return None
            the_date = None
            try:
                the_date = datetime.fromisoformat(date_str).date()
            except Exception:
                try:
                    the_date = datetime.fromisoformat(date_str.split('T')[0]).date()
                except Exception:
                    return None
            year = the_date.year
            month = the_date.month
            day = the_date.day
            iso_week = the_date.isocalendar()[1]
            with self.connection.cursor() as cursor:
                cursor.execute(f"""
                SELECT date_dim_id FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_date
                WHERE the_date = ?
                """, (the_date,))
                result = cursor.fetchone()
                if result:
                    return result[0]
                cursor.execute(f"""
                INSERT INTO {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_date (the_date, year, month, day, iso_week)
                VALUES (?, ?, ?, ?, ?)
                """, (the_date, year, month, day, iso_week))
                cursor.execute(f"""
                SELECT date_dim_id FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_date
                WHERE the_date = ?
                """, (the_date,))
                return cursor.fetchone()[0]
        except Exception as e:
            print(f"Error with date lookup: {e}")
            return None

