from databricks import sql
from typing import Dict, Any, List
import config
from datetime import datetime


class DatabricksHandler:
    def __init__(self):
        self.connection = None
        self.connect()
    
    def connect(self):
        """Establish connection to Databricks"""
        try:
            self.connection = sql.connect(
                server_hostname=config.DATABRICKS_HOST,
                http_path=config.DATABRICKS_HTTP_PATH,
                personal_access_token=config.DATABRICKS_TOKEN
            )
            print("Connected to Databricks successfully")
        except Exception as e:
            print(f"Error connecting to Databricks: {e}")
            raise
    
    def create_table_if_not_exists(self):
        """Create the job applications table if it doesn't exist"""
        try:
            with self.connection.cursor() as cursor:
                create_table_query = f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.{config.DATABRICKS_TABLE} (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                    message_id STRING NOT NULL UNIQUE,
                    from_email STRING,
                    to_email STRING,
                    subject STRING,
                    email_date STRING,
                    received_timestamp TIMESTAMP,
                    company STRING,
                    job_title STRING,
                    application_status STRING,
                    application_url STRING,
                    email_body STRING,
                    keywords_found STRING,
                    processed_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """
                cursor.execute(create_table_query)
                print(f"Table {config.DATABRICKS_TABLE} ready")
        except Exception as e:
            print(f"Error creating table: {e}")
    def create_tables_if_not_exist(self):
        """Create both OLTP (transactional) and OLAP (analytics) table schemas"""
        try:
            with self.connection.cursor() as cursor:
                # ===== TRANSACTIONAL SCHEMA (Star Schema - OLTP) =====

                # Dimension: Company
                cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_company (
                    company_dim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company_name STRING NOT NULL UNIQUE,
                    domain STRING,
                    first_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """)

                # Dimension: Job Title
                cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_job_title (
                    job_title_dim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title STRING NOT NULL UNIQUE,
                    category STRING,
                    first_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """)

                # Dimension: Date (simple date dimension)
                cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_date (
                    date_dim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    the_date DATE NOT NULL UNIQUE,
                    year INT,
                    month INT,
                    day INT,
                    iso_week INT
                )
                """)

                # Dimension: Email Sender
                cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_sender (
                    sender_dim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sender_email STRING NOT NULL UNIQUE,
                    sender_name STRING
                )
                """)

                # Fact table: Applications
                cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.fact_applications (
                    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    message_id STRING NOT NULL UNIQUE,
                    company_dim_id BIGINT,
                    job_title_dim_id BIGINT,
                    sender_dim_id BIGINT,
                    date_dim_id BIGINT,
                    to_email STRING,
                    subject STRING,
                    application_status STRING,
                    application_url STRING,
                    received_timestamp TIMESTAMP,
                    email_body STRING,
                    keywords STRING,
                    processed_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """)
                
                # ===== ANALYTICS SCHEMA (Denormalized - OLAP) =====
                
                # Denormalized analytics view
                cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.applications_analytics (
                    application_id BIGINT,
                    message_id STRING,
                    company_name STRING,
                    company_id BIGINT,
                    job_title STRING,
                    job_title_id BIGINT,
                    from_email STRING,
                    to_email STRING,
                    subject STRING,
                    email_date STRING,
                    application_status STRING,
                    application_url STRING,
                    received_timestamp TIMESTAMP,
                    keywords_found STRING,
                    email_body_length INT,
                    processed_timestamp TIMESTAMP,
                    synced_to_analytics TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """)
                
                print("✓ Transactional (OLTP) schema created")
                print("✓ Analytics (OLAP) schema created")
        
        except Exception as e:
            print(f"Error creating tables: {e}")
    
    def get_or_create_company(self, company_name: str) -> int:
        """Get company_dim_id or create new company dimension"""
        try:
            with self.connection.cursor() as cursor:
                cursor.execute(f"""
                SELECT company_dim_id FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_company
                WHERE company_name = ?
                """, (company_name,))
                result = cursor.fetchone()
                if result:
                    return result[0]
                cursor.execute(f"""
                INSERT INTO {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_company (company_name)
                VALUES (?)
                """, (company_name,))
                cursor.execute(f"""
                SELECT company_dim_id FROM {config.DATABRICKS_CATALOG}.{config.DATABRICKS_SCHEMA}.dim_company
                WHERE company_name = ?
                """, (company_name,))
                return cursor.fetchone()[0]
        except Exception as e:
            print(f"Error with company lookup: {e}")
            return None
    
